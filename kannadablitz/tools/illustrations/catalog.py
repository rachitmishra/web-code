#!/usr/bin/env python3
"""Moves nothing; (re)generates src/content/packs/kn/illustrations/catalog.json + README index.

Every vocabulary word maps to an illustration file named after its English meaning
(see slug() — must match illustrationName() in illustrations/index.ts). Drop a file
with that name (.svg, .png, .jpg or .webp) into the folder and the app picks it up.
"""
import json, re, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
PACK = ROOT / "src/content/packs/kn"
DIR = PACK / "illustrations"

def slug(meaning: str) -> str:
    m = re.sub(r"\([^)]*\)", "", meaning.lower())
    m = re.split(r"[,;/]", m)[0]
    m = re.sub(r"[^a-z0-9]+", "-", m).strip("-")
    return m[:40].strip("-") or "untitled"

vocab = json.loads((PACK / "vocab.json").read_text())
files = {p.stem: p.name for p in DIR.iterdir() if p.suffix in {".svg", ".png", ".jpg", ".jpeg", ".webp"}}

entries = {}
for v in vocab:
    name = v.get("art") or slug(v["meaning"])
    e = entries.setdefault(name, {"name": name, "file": files.get(name), "kind": "word", "topic": v["topic"], "description": "", "words": []})
    e["words"].append({"id": v["id"], "script": v["script"], "roman": v["roman"], "meaning": v["meaning"]})
for e in entries.values():
    w = e["words"][0]
    e["description"] = (f"Illustration of \"{w['meaning']}\" (topic: {e['topic']}). Single clear subject, centred, flat shapes, "
                        "fine maroon outline (#3B1214) on sandalwood paper (#FFF7E6), accents of kumkuma red (#C8102E), "
                        "arishina yellow (#F2B705) and leaf green (#2E7A3C). No text. Square 1:1, viewBox 0 0 200 200.")
    e["status"] = "done" if e["file"] else "needed (falls back to the topic motif)"

postcards = []
for p in sorted(DIR.glob("postcard-*")):
    postcards.append({"name": p.stem, "file": p.name, "kind": "postcard",
                      "description": "Postcard scene, landscape 360x190, same palette and outline style as word art."})

out = {"_readme": "Generated by tools/illustrations/catalog.py. Edit the image files, not this list.",
       "words": sorted(entries.values(), key=lambda e: (e["status"] != "done", e["name"])), "postcards": postcards}
(DIR / "catalog.json").write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n")
done = sum(1 for e in entries.values() if e["file"])
print(f"{len(entries)} word illustrations ({done} done, {len(entries)-done} needed), {len(postcards)} postcards", file=sys.stderr)
